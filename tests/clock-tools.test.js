const assert = require('assert');
const tools = require('../shell/logic/clocktools.js');
const state = tools.emptyState();
let timer = tools.timerAction(state.timer, 'start', 10000, 5000);
assert.equal(tools.timerRemaining(timer, 12000), 3000);
// Restart and suspend are represented by a gap in ticks, not extended duration.
let restored = tools.readState(JSON.stringify({...state, timer})).state;
assert.equal(tools.timerRemaining(restored.timer, 19000), 0);
timer = tools.timerAction(restored.timer, 'finish', 19000);
assert.equal(timer.status, 'finished');
timer = tools.timerAction(timer, 'reset', 20000);
assert.equal(timer.remaining, 5000);
assert.equal(timer.status, 'ready');
timer = tools.timerAction(timer, 'start', 20000, 10000);
timer = tools.timerAction(timer, 'pause', 23000);
assert.equal(timer.remaining, 7000);
assert.equal(tools.timerRemaining(timer, 99000), 7000);
timer = tools.timerAction(timer, 'resume', 100000);
assert.equal(timer.deadline, 107000);
assert.equal(tools.timerAction(timer, 'start', 100000, NaN).deadline, 107000);
assert.equal(tools.timerAction(timer, 'start', 100000, 0).deadline, 107000);
assert.equal(tools.timerAction(timer, 'start', 100000, 604800001).deadline, 107000);
let stopwatch = tools.stopwatchAction(state.stopwatch, 'start', 1000);
stopwatch = tools.stopwatchAction(stopwatch, 'lap', 2300);
stopwatch = tools.stopwatchAction(stopwatch, 'pause', 4200);
assert.equal(stopwatch.elapsed, 3200);
assert.deepEqual(stopwatch.laps, [1300]);
assert.equal(tools.stopwatchElapsed(stopwatch, 90000), 3200);
stopwatch = tools.stopwatchAction(stopwatch, 'start', 100000);
assert.equal(tools.stopwatchElapsed(stopwatch, 102000), 5200);
assert.equal(tools.stopwatchElapsed(stopwatch, 99000), 3200);
restored = tools.readState(JSON.stringify({...state, stopwatch})).state;
assert.equal(tools.stopwatchElapsed(restored.stopwatch, 110000), 13200);
for(let i=0; i<100; i++) stopwatch = tools.stopwatchAction(stopwatch, 'lap', 110000 + i);
assert.equal(stopwatch.laps.length, 50);
stopwatch = tools.stopwatchAction(stopwatch, 'reset', 120000);
assert.equal(stopwatch.status, 'ready');
assert.equal(stopwatch.elapsed, 0);
assert.deepEqual(stopwatch.laps, []);
assert.equal(tools.readState('bad').ok, false);
assert.equal(tools.readState('{"version":2}').ok, false);
assert.equal(tools.normalize({stopwatch:{laps:[2,1,4,-1,NaN]}}).stopwatch.laps.join(','), '2,4');
assert.equal(tools.durationText(1, false), '00:01');
assert.equal(tools.durationText(3600000, false), '01:00:00');
assert.equal(tools.durationText(12345, true), '00:12.34');
assert.equal(tools.durationText(-1, true), '00:00.00');
console.log('clock tools: deadline/suspend/restart, pause/resume, laps, validation and display passed');
