const assert=require('node:assert/strict');
const S=require('../shell/logic/settings.js'),B=require('../shell/logic/bar.js'),C=require('../shell/logic/clock.js'),P=require('../shell/logic/popover.js');
const date=new Date(2026,10,1,0,7,5);
assert.equal(C.formatTime(date,true,true),'00:07:05');
assert.equal(C.formatTime(date,false,true),'12:07:05 AM');
assert.equal(C.formatTime(date,false,false),'12:07 AM');
assert.equal(C.datePattern('iso'),'yyyy-MM-dd');
assert.equal(C.formatTime({getHours:()=>1,getMinutes:()=>2,getSeconds:()=>99},true,true),'--:--');
const before=S.validateSettings({bar:{moduleOrder:['clock','workspaces','title','search']},clock:{use24Hour:false}});
assert.equal(before.ok,true);assert.equal(before.settings.clock.use24Hour,false);assert.equal(before.settings.clock.showSeconds,false);assert.equal(before.settings.bar.searchLabel,false);
assert.equal(B.moduleSide('clock','{}',before.settings.bar.moduleOrder),'left');
assert.equal(B.moduleSide('search','{}',before.settings.bar.moduleOrder),'right');
assert.equal(B.moduleSide('clock','{"clock":"center"}',before.settings.bar.moduleOrder),'center');
assert.deepEqual(B.hiddenForOutput(['tray'],'{"DP-1":["clock"]}','DP-1'),['clock']);
assert.deepEqual(B.hiddenForOutput(['tray'],'{"DP-1":["clock"]}','HDMI-A-1'),['tray']);
assert.deepEqual(B.modulesForSide(B.BAR_MODULES,[],'{"clock":"center"}','center'),['title','clock']);
for(const bar of [{moduleSidesJson:'{"clock":"bottom"}'},{hiddenOutputsJson:'{"DP-1":["made-up"]}'},{hiddenOutputsJson:'{"DP-1":"clock"}'}]) assert.equal(S.validateSettings({bar}).ok,false);
assert.equal(P.reducePopup(P.popupModel(),{type:'toggle',id:'customize'},{instantOpen:true}).panelId,'customize');
console.log('bar clock formats, inherited placement, per-output visibility and context-menu state passed');
